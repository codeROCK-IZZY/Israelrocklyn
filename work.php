<?php
/** A project case study: /work/<slug> (rewritten to work.php?slug=<slug> by .htaccess). */

declare(strict_types=1);

require __DIR__ . '/app/bootstrap.php';

$slug = (string) ($_GET['slug'] ?? '');
$projects = projects();
if (!preg_match('/^[a-z0-9-]{1,64}$/', $slug) || !isset($projects[$slug])) {
    require __DIR__ . '/404.php';
    exit;
}
$x = $projects[$slug];
$slugs = array_keys($projects);
$next = $slugs[(array_search($slug, $slugs, true) + 1) % count($slugs)];
$area = ['ai' => 'AI & LLM', 'ml' => 'Machine learning', 'platform' => 'Cloud & platform'][$x['area']];

send_page_headers();
header('Cache-Control: public, max-age=600');

view('head', [
    'title' => $x['title'] . ' · Case study · Israel Rocklyn',
    'description' => $x['tagline'] . ' ' . $x['results'][0][0] . ' ' . $x['results'][0][1] . '.',
    'path' => '/work/' . $slug,
    'jsonld' => [
        '@context' => 'https://schema.org',
        '@type' => 'SoftwareSourceCode',
        'name' => $x['title'],
        'description' => $x['tagline'],
        'codeRepository' => $x['repo'],
        'programmingLanguage' => $x['stack'],
        'author' => ['@type' => 'Person', 'name' => profile()['name'], 'url' => SITE_URL . '/'],
    ],
]);
?>
<article class="case wrap">
  <nav class="crumbs" aria-label="Breadcrumb"><a href="/#work">Work</a> <span aria-hidden="true">/</span> <span><?= e($x['title']) ?></span></nav>
  <header class="case-head">
    <p class="kicker"><?= e($area) ?></p>
    <h1><?= e($x['title']) ?></h1>
    <p class="lede"><?= e($x['tagline']) ?></p>
    <p class="links"><a class="button" href="<?= e($x['repo']) ?>" rel="noopener">View the code on GitHub</a></p>
  </header>

<?php if ($x['image']): ?>
  <figure class="case-figure">
    <img src="/assets/img/<?= e($x['image']) ?>" alt="<?= e($x['image_alt']) ?>" width="1280" height="800" decoding="async">
    <figcaption><?= e($x['image_alt']) ?>. Screenshot from the project's demo (synthetic data).</figcaption>
  </figure>
<?php endif; ?>

  <section class="case-results" aria-label="Results">
<?php foreach ($x['results'] as [$value, $label]): ?>
    <p><strong><?= e($value) ?></strong><span><?= e($label) ?></span></p>
<?php endforeach; ?>
  </section>

  <div class="case-body">
    <section>
      <h2>The problem</h2>
      <p><?= e($x['problem']) ?></p>
    </section>
    <section>
      <h2>What I built</h2>
      <ul class="checklist">
<?php foreach ($x['built'] as $b): ?>
        <li><?= e($b) ?></li>
<?php endforeach; ?>
      </ul>
    </section>
    <section>
      <h2>Stack</h2>
      <p class="tags tags-lg"><?= e(implode(' · ', $x['stack'])) ?></p>
      <p class="muted">The repository has the full design document, operations runbook, evaluation report and known limitations. All data is synthetic, generated by code in the repository.</p>
    </section>
  </div>

  <nav class="case-next" aria-label="Next project">
    <p class="muted">Next project</p>
    <a href="/work/<?= e($next) ?>"><?= e($projects[$next]['title']) ?></a>
  </nav>
</article>
<?php view('foot'); ?>
